"""Download official factual calendars, validate and pack five years for offline use."""
from pathlib import Path
import calendar, csv, datetime as dt, hashlib, io, json, re, subprocess, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor

ROOT = Path(__file__).resolve().parent
INSTALLED = ROOT.name == 'tools'
RAW = ROOT / ('calendar-data' if INSTALLED else 'data')
RAW.mkdir(exist_ok=True)
YEARS = range(2026, 2031)
MONTHS = ['正月','二月','三月','四月','五月','六月','七月','八月','九月','十月','十一月','十二月']
DAYS = ['初一','初二','初三','初四','初五','初六','初七','初八','初九','初十','十一','十二','十三','十四','十五','十六','十七','十八','十九','二十','廿一','廿二','廿三','廿四','廿五','廿六','廿七','廿八','廿九','三十']
TERMS = ['小寒','大寒','立春','雨水','驚蟄','春分','清明','穀雨','立夏','小滿','芒種','夏至','小暑','大暑','立秋','處暑','白露','秋分','寒露','霜降','立冬','小雪','大雪','冬至']

def download(item):
    year, kind = item
    if kind == 'csv':
        url = f'https://data.weather.gov.hk/weatherAPI/hko_data/calendar/nongli_calendar_{year}.csv'
    else:
        url = f'https://www.hko.gov.hk/tc/gts/time/calendar/text/files/T{year}c.txt'
    target = RAW / f'{year}.{kind}'
    if not target.exists():
        if sys.platform == 'win32':
            # Validate TLS chain/hostname; tolerate only an unavailable revocation server.
            subprocess.run(['curl.exe','--ssl-revoke-best-effort','--fail','--silent','--show-error',
                            '--connect-timeout','10','--max-time','30','--retry','1',
                            '--output',str(target),url],check=True)
        else:
            with urllib.request.urlopen(url, timeout=35) as response:
                data = response.read()
            target.write_bytes(data)
    return {'year':year,'kind':kind,'url':url,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}

with ThreadPoolExecutor(max_workers=5) as pool:
    sources = list(pool.map(download, [(2026,'csv')]+[(y,'txt') for y in YEARS]))

packed = []
fixtures = []
csv_rows = list(csv.reader(io.StringIO((RAW / '2026.csv').read_text(encoding='utf-8-sig'))))[1:]
lm = MONTHS.index(csv_rows[0][3]) + 1
leap = False
previous_day = None
for year in YEARS:
    terms = {}
    text_rows = {}
    for line in (RAW / f'{year}.txt').read_text(encoding='utf-8-sig').splitlines():
        parts = line.split()
        if not parts or not re.fullmatch(r'\d{4}年\d{1,2}月\d{1,2}日', parts[0]):
            continue
        y,m,d = map(int,re.findall(r'\d+',parts[0]))
        date = dt.date(y,m,d)
        assert parts[2] == ['星期一','星期二','星期三','星期四','星期五','星期六','星期日'][date.weekday()], parts
        text_rows[date] = parts[1]
        if len(parts) == 4:
            assert parts[3] in TERMS, parts
            terms[dt.date(y,m,d)] = TERMS.index(parts[3]) + 1
    assert len(text_rows) == 365 + calendar.isleap(year), (year,len(text_rows))
    assert sorted(terms.values()) == list(range(1,25)), (year,terms)
    for i in range(len(text_rows)):
        date = dt.date(year,1,1) + dt.timedelta(days=i)
        txt_day = text_rows[date]
        if txt_day.endswith('月'):
            leap = txt_day.startswith(('閏','闰'))
            lm = MONTHS.index(txt_day.lstrip('閏闰')) + 1
            ld = 1
            assert previous_day in (29,30), (date,previous_day)
        else:
            ld = DAYS.index(txt_day) + 1
            if previous_day is not None: assert ld == previous_day + 1, (date,ld,previous_day)
        previous_day = ld
        if year == 2026:
            row = csv_rows[i]
            assert row[3] == ('閏' if leap else '') + MONTHS[lm-1] and row[4] == DAYS[ld-1], (date,row,lm,ld)
        term = terms.get(date,0)
        value = ld | lm << 5 | int(leap) << 9 | term << 10
        assert 0 < value < 32768
        packed.append(value)
        fixtures.append({'date':str(date),'lunarMonth':lm,'lunarDay':ld,'leap':leap,'termIndex':term})

lines = ['#pragma once', '#include <stdint.h>', '', '// Generated by tools/generate_calendar_data.py from HKO CSV + text; see CALENDAR.md.', '// Bits: day[0..4], month[5..8], leap[9], solar-term index[10..14].', 'namespace calendar_data {', 'static constexpr int kFirstYear = 2026;', 'static constexpr int kLastYear = 2030;', 'static constexpr uint16_t kDays[] = {']
for i in range(0,len(packed),16):
    lines.append('  ' + ','.join(str(v) for v in packed[i:i+16]) + ',')
lines += ['};', 'static_assert(sizeof(kDays)/sizeof(kDays[0]) == 1826, "Calendar table must cover 2026-2030");', '} // namespace calendar_data', '']
(ROOT.parent / 'src/CalendarData.h' if INSTALLED else ROOT / 'CalendarData.h').write_text('\n'.join(lines),encoding='utf-8')
(RAW / 'sources.json').write_text(json.dumps(sources,ensure_ascii=False,indent=2),encoding='utf-8')
(ROOT / 'fixtures.json').write_text(json.dumps(fixtures,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
print(f'Validated {len(packed)} consecutive HKO dates and weekdays; 2026 independently cross-checked against CSV; {len(YEARS)*24} solar terms; packed bytes={len(packed)*2}.')
